#!/usr/bin/env node
import { ethers } from "ethers";
import fs from "fs";

console.log("\n=== Test Wallet Setup ===\n");

// Generate a test wallet
const testWallet = ethers.Wallet.createRandom();

console.log("Generated test wallet for fee collection:");
console.log("Address:", testWallet.address);
console.log("Private Key:", testWallet.privateKey);

// Generate a revenue wallet  
const revenueWallet = ethers.Wallet.createRandom();

console.log("\nGenerated revenue wallet (where fees will be sent):");
console.log("Address:", revenueWallet.address);
console.log("Private Key:", revenueWallet.privateKey);

// Create test .env content
const envContent = `# Test Configuration (DO NOT USE IN PRODUCTION)
# Generated by setup-test-wallet.js

# Revenue collection wallet (collects fees from users)
REVENUE_PRIVATE_KEY=${testWallet.privateKey}

# Revenue destination wallet (where accumulated fees are sent)
REVENUE_WALLET=${revenueWallet.address}

# Admin API key for dashboard
ADMIN_API_KEY=test-admin-key-${Date.now()}

# Add your RPC URLs here
ETHEREUM_RPC=https://eth.llamarpc.com
ARBITRUM_RPC=https://arb1.arbitrum.io/rpc
POLYGON_RPC=https://polygon-rpc.com
`;

// Save to a test env file
const testEnvPath = ".env.test";
fs.writeFileSync(testEnvPath, envContent);

console.log(`\n✅ Test configuration saved to ${testEnvPath}`);
console.log("\n=== Instructions ===\n");
console.log("1. For TESTING ONLY (no real money):");
console.log("   cp .env.test .env");
console.log("   node scripts/test-revenue-system.js");
console.log("");
console.log("2. For PRODUCTION (real money):");
console.log("   - Use your actual wallets in .env");
console.log("   - Fund the fee collection wallet with ETH for gas");
console.log("   - Keep private keys secure!");
console.log("");
console.log("3. To test with testnet:");
console.log("   - Use testnet RPC URLs (Goerli, Mumbai, etc)");
console.log("   - Get testnet ETH from faucets");
console.log("   - Deploy contracts on testnet");
console.log("\n⚠️  WARNING: Never commit .env files with real private keys!\n");
async function runSpecificFix(fileName, issue) {
    const claude = new ClaudeCodeAssistant();
    console.log(`🔧 Generating specific fix for ${fileName}...`);
    
    try {
        const fix = await claude.generateSpecificFix(fileName, issue);
        const outputFile = `/workspace/.claude-output/fix-${fileName.replace('/', '-')}.md`;
        fs.writeFileSync(outputFile, fix);
        console.log(`✅ Fix generated: ${outputFile}`);
    } catch (error) {
        console.error(`❌ Error generating fix for ${fileName}:`, error.message);
    }
}

// Command line interface
const args = process.argv.slice(2);
if (args[0] === 'fix' && args[1]) {
    runSpecificFix(args[1], args[2] || 'General fixes needed');
} else if (args[0] === 'analyze') {
    (async () => {
        const claude = new ClaudeCodeAssistant();
        await claude.analyzeProject();
    })();
} else if (args[0] === 'ui-fixes') {
    (async () => {
        const claude = new ClaudeCodeAssistant();
        await claude.fixUIIssues();
    })();
} else {
    // Run full workflow if called directly
    if (require.main === module) {
        autoFixWorkflow();
    }
}

module.exports = { autoFixWorkflow, runSpecificFix, runAnalysisOnly, runUIFixesOnly, runFullWorkflow };

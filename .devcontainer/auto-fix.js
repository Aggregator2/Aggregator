const ClaudeCodeAssistant = require('./claude-api');
const fs = require('fs');
const { execSync } = require('child_process');

async function autoFixWorkflow(command = 'full') {
    const claude = new ClaudeCodeAssistant();
    
    try {
        console.log('🚀 Starting Meta Aggregator 2.0 Auto-Fix Workflow...');
        console.log('🔑 API Key configured:', process.env.ANTHROPIC_API_KEY ? 'YES' : 'NO');
        
        // Check command type
        switch (command) {
            case 'analyze':
                await runAnalysisOnly(claude);
                break;
            case 'ui-only':
                await runUIFixesOnly(claude);
                break;
            case 'fix':
            case 'full':
            default:
                await runFullWorkflow(claude);
                break;
        }
        
    } catch (error) {
        console.error('❌ Error in auto-fix workflow:', error.message);
        if (error.message.includes('credit') || error.message.includes('rate limit')) {
            console.error('� Check your Anthropic API credits/rate limits in the dashboard');
        }
    }
}

async function runAnalysisOnly(claude) {
    console.log('\n📋 Running Project Analysis...');
    const analysis = await claude.analyzeProject();
    console.log('✅ Analysis complete - saved to .claude-output/analysis.md');
    
    await generateAnalysisReport(analysis);
}

async function runUIFixesOnly(claude) {
    console.log('\n🔧 Running UI Fixes Generation...');
    const fixes = await claude.fixUIIssues();
    console.log('✅ UI fixes generated - saved to .claude-output/ui-fixes.md');
    
    await generateUIFixesReport(fixes);
}

async function runFullWorkflow(claude) {
    console.log('\n📋 Phase 1: Project Analysis...');
    const analysis = await claude.analyzeProject();
    console.log('✅ Analysis complete');
    
    console.log('\n🔧 Phase 2: UI Fixes Generation...');
    const fixes = await claude.fixUIIssues();
    console.log('✅ UI fixes generated');
    
    console.log('\n📝 Phase 3: Implementation Ready');
    console.log('📁 Check these files for detailed fixes:');
    console.log('   - claude-session.log (full session log)');
    console.log('   - .claude-output/analysis.md (project analysis)');
    console.log('   - .claude-output/ui-fixes.md (specific fixes)');
    
    console.log('\n🎯 Next Steps:');
    console.log('1. Review the generated fixes in .claude-output/');
    console.log('2. Apply fixes to your source files');
    console.log('3. Test the changes');
    console.log('4. Run: npm run build (to verify fixes)');
    
    // Generate summary
    await generateSummary(analysis, fixes);
}

